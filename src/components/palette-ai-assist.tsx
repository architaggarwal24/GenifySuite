"use client";

import { useState } from "react";
import { AiAssistSection } from "@/components/ai-assist-section";
import { Button } from "@/components/ui/button";
import { Input, Label } from "@/components/ui/input";
import { useAiRun } from "@/hooks/use-ai-run";
import { type HarmonyType } from "@/lib/color";

export interface VibeResult {
  name: string;
  base: string;
  harmony: HarmonyType;
}

export function PaletteAiAssist({ onVibe }: { onVibe: (vibe: VibeResult) => void }) {
  const { run, loading, error } = useAiRun();
  const [vibe, setVibe] = useState("");

  return (
    <AiAssistSection title="Describe a vibe">
      {(selection) => (
        <div>
          <Label htmlFor="palette-vibe">Mood or style</Label>
          <div className="flex flex-col gap-2 sm:flex-row">
            <Input
              id="palette-vibe"
              placeholder="e.g. moody cyberpunk noir, or calm coastal morning"
              value={vibe}
              onChange={(e) => setVibe(e.target.value)}
            />
            <Button
              disabled={!selection || loading || !vibe.trim()}
              onClick={async () => {
                const result = await run<VibeResult>("palette", { vibe }, selection);
                if (result) onVibe(result);
              }}
            >
              {loading ? "Thinking…" : "Pick colors"}
            </Button>
          </div>
          {error && (
            <p role="alert" className="mt-2 text-sm text-rust">
              {error}
            </p>
          )}
          <p className="mt-2 text-xs text-paper-faint">
            The AI chooses a base color and harmony; the palette itself is still generated by the tool above.
          </p>
        </div>
      )}
    </AiAssistSection>
  );
}
